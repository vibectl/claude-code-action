/**
 * Authentication Bridge — Configures container credentials for vibectl execution.
 *
 * Bridges vibectl's authentication model to CCA's expected environment:
 * - GitHub installation token → GITHUB_TOKEN, GH_TOKEN
 * - AI proxy URL → ANTHROPIC_BASE_URL with proxy headers
 * - GitHub egress proxy → GITHUB_API_URL + fetch interceptor
 * - Bot identity → BOT_USER_ID, BOT_LOGIN
 * - MCP server paths → GITHUB_ACTION_PATH
 * - Workflow tokens → DEFAULT_WORKFLOW_TOKEN
 *
 * Per EP150 Section 9: OIDC exchange (token.ts) is entirely bypassed.
 * The entry adapter calls CCA internal functions directly, so
 * setupGitHubToken() is never invoked. token.ts remains dead code
 * (zero diff, zero merge conflict risk).
 */

import { mkdtemp, writeFile } from "fs/promises";
import { join } from "path";
import { tmpdir } from "os";
import { installFetchInterceptor } from "./fetch-interceptor.ts";

/**
 * Task payload credentials provided by vibectl runner worker.
 *
 * GitHub-specific fields are optional to support prompt-only execution
 * where no GitHub webhook context exists. When contextJson is absent
 * from the payload, only aiProxyUrl and proxyHeaders are required.
 */
export interface TaskCredentials {
  /** GitHub installation token (ghs_xxx) generated by runner worker (optional for prompt-only) */
  githubToken?: string;
  /** AI proxy base URL for Anthropic API requests */
  aiProxyUrl: string;
  /** Proxy authentication headers (X-Proxy-Token) */
  proxyHeaders: Record<string, string>;
  /** Repository owner (optional for prompt-only) */
  repoOwner?: string;
  /** Repository name (optional for prompt-only) */
  repoName?: string;
  /** Event name (issue_comment, pull_request, etc.) (optional for prompt-only) */
  eventName?: string;
  /** Bot user ID for the vibectl GitHub App (optional for prompt-only) */
  botUserId?: string;
  /** Bot login name for the vibectl GitHub App (optional for prompt-only) */
  botLogin?: string;
  /** CCA source path in container (default: /opt/cca) */
  ccaSourcePath?: string;
  /** GitHub egress proxy URL — when set, GITHUB_API_URL redirects all CCA Octokit calls */
  githubApiUrl?: string;
  /** HMAC proxy authentication token (format: {expiry}:{base64_signature}) */
  githubProxyToken?: string;
  /** Egress scanning mode: 'full' (scan + inject) or 'relay' (inject only) */
  egressMode?: "full" | "relay";
}

/**
 * Configure the container environment for CCA execution.
 *
 * Sets process.env variables that CCA's internal functions read.
 * This replaces CCA's OIDC-based token setup (token.ts) with
 * vibectl's direct credential injection.
 *
 * Returns the temp directory path used for GitHub Actions file-based outputs.
 */
export async function configureAuth(
  credentials: TaskCredentials,
): Promise<{ tempDir: string }> {
  // Create temp directory for @actions/core file-based outputs
  const tempDir = await mkdtemp(join(tmpdir(), "vibectl-"));

  // GitHub token — used by MCP servers and git operations
  process.env.GITHUB_TOKEN = credentials.githubToken;
  process.env.GH_TOKEN = credentials.githubToken;

  // AI proxy — transparent to Claude Code SDK
  // SDK sends to ANTHROPIC_BASE_URL, proxy injects real API key server-side
  process.env.ANTHROPIC_BASE_URL = credentials.aiProxyUrl;
  process.env.ANTHROPIC_API_KEY = "dummy-key-replaced-by-ai-proxy";

  // Proxy authentication headers
  // Trusted source: proxyHeaders (e.g., X-Proxy-Token) come from the vibectl
  // runner worker's task dispatch, not from user input. JSON injection is not
  // a concern because the runner worker constructs these headers server-side.
  const headerEntries = Object.entries(credentials.proxyHeaders);
  if (headerEntries.length > 0) {
    // ANTHROPIC_CUSTOM_HEADERS format: "Name: Value" (per Claude Code docs)
    // Multiple headers separated by newlines.
    process.env.ANTHROPIC_CUSTOM_HEADERS = headerEntries
      .map(([name, value]) => `${name}: ${value}`)
      .join("\n");
  }

  // Bot identity — read by constants.ts (Phase 2 patch)
  process.env.BOT_USER_ID = credentials.botUserId;
  process.env.BOT_LOGIN = credentials.botLogin;

  // CCA source path — used by install-mcp-server.ts for MCP server script paths
  process.env.GITHUB_ACTION_PATH = credentials.ccaSourcePath || "/opt/cca";

  // GitHub context env vars — read by various CCA components
  process.env.GITHUB_EVENT_NAME = credentials.eventName;
  process.env.GITHUB_SERVER_URL =
    process.env.GITHUB_SERVER_URL || "https://github.com";

  // Workflow token — used by CI MCP server for actions:read permission
  // In vibectl, the installation token serves both purposes
  process.env.DEFAULT_WORKFLOW_TOKEN = credentials.githubToken;

  // Runner temp directory — used by CCA for prompt files and execution output
  process.env.RUNNER_TEMP = tempDir;

  // @actions/core file-based output paths (defense-in-depth)
  // These files capture core.setOutput() and core.exportVariable() calls
  // from CCA during execution.
  //
  // EP152 output parsing contract:
  //   GITHUB_OUTPUT format: key=value pairs (one per line), or
  //     key<<delimiter / value / delimiter for multiline values.
  //   GITHUB_ENV format: same as GITHUB_OUTPUT.
  //   Runner worker reads these files after execution to extract
  //   CCA results (e.g., conclusion, session ID, execution file path).
  const outputFile = join(tempDir, "github-output");
  const envFile = join(tempDir, "github-env");
  await writeFile(outputFile, "");
  await writeFile(envFile, "");
  process.env.GITHUB_OUTPUT = outputFile;
  process.env.GITHUB_ENV = envFile;

  // Workspace directory — where the cloned repo lives in the container
  process.env.GITHUB_WORKSPACE = process.env.GITHUB_WORKSPACE || "/workspace";

  // GitHub egress proxy — redirects all CCA GitHub API calls through
  // the centralized proxy. CCA's src/github/api/config.ts reads GITHUB_API_URL
  // to set Octokit baseUrl, so all REST and GraphQL calls are redirected.
  // MCP server processes also receive GITHUB_API_URL via install-mcp-server.ts.
  if (credentials.githubApiUrl) {
    process.env.GITHUB_API_URL = credentials.githubApiUrl;
  }

  // Fetch interceptor — injects X-Proxy-Token and X-Egress-Mode headers
  // on requests matching the GitHub proxy URL. Only installed when the
  // proxy token is present (no-op otherwise, global fetch stays unmodified).
  if (credentials.githubProxyToken && credentials.githubApiUrl) {
    installFetchInterceptor({
      githubApiUrl: credentials.githubApiUrl,
      proxyToken: credentials.githubProxyToken,
      egressMode: credentials.egressMode || "full",
    });
  }

  return { tempDir };
}

/**
 * Configure the minimal container environment for prompt-only execution.
 *
 * Sets only the environment variables needed for Agent SDK execution
 * via AI proxy — no GitHub tokens, no bot identity, no egress proxy.
 * This function is used when the task payload has no contextJson
 * (no webhook trigger, no GitHub repository reference).
 *
 * Returns the temp directory path used for execution output files.
 */
export async function configurePromptOnlyAuth(
  credentials: Pick<TaskCredentials, "aiProxyUrl" | "proxyHeaders" | "ccaSourcePath">,
): Promise<{ tempDir: string }> {
  // Create temp directory for execution output files
  const tempDir = await mkdtemp(join(tmpdir(), "vibectl-"));

  // AI proxy — transparent to Claude Code SDK
  process.env.ANTHROPIC_BASE_URL = credentials.aiProxyUrl;
  process.env.ANTHROPIC_API_KEY = "dummy-key-replaced-by-ai-proxy";

  // Proxy authentication headers
  const headerEntries = Object.entries(credentials.proxyHeaders);
  if (headerEntries.length > 0) {
    process.env.ANTHROPIC_CUSTOM_HEADERS = headerEntries
      .map(([name, value]) => `${name}: ${value}`)
      .join("\n");
  }

  // CCA source path — used by install-mcp-server.ts for MCP server script paths
  process.env.GITHUB_ACTION_PATH = credentials.ccaSourcePath || "/opt/cca";

  // Runner temp directory — used for prompt files and execution output
  process.env.RUNNER_TEMP = tempDir;

  // @actions/core file-based output paths (defense-in-depth)
  const outputFile = join(tempDir, "github-output");
  const envFile = join(tempDir, "github-env");
  await writeFile(outputFile, "");
  await writeFile(envFile, "");
  process.env.GITHUB_OUTPUT = outputFile;
  process.env.GITHUB_ENV = envFile;

  // Workspace directory — where the working directory lives in the container
  process.env.GITHUB_WORKSPACE = process.env.GITHUB_WORKSPACE || "/workspace";

  return { tempDir };
}
