/**
 * Authentication Bridge — Configures container credentials for vibectl execution.
 *
 * Bridges vibectl's authentication model to CCA's expected environment:
 * - GitHub installation token → GITHUB_TOKEN, GH_TOKEN
 * - AI proxy URL → ANTHROPIC_BASE_URL with proxy headers
 * - Bot identity → BOT_USER_ID, BOT_LOGIN
 * - MCP server paths → GITHUB_ACTION_PATH
 * - Workflow tokens → DEFAULT_WORKFLOW_TOKEN
 *
 * Per EP150 Section 9: OIDC exchange (token.ts) is entirely bypassed.
 * The entry adapter calls CCA internal functions directly, so
 * setupGitHubToken() is never invoked. token.ts remains dead code
 * (zero diff, zero merge conflict risk).
 */

import { mkdtemp, writeFile } from "fs/promises";
import { join } from "path";
import { tmpdir } from "os";

/**
 * Task payload credentials provided by vibectl runner worker.
 */
export interface TaskCredentials {
  /** GitHub installation token (ghs_xxx) generated by runner worker */
  githubToken: string;
  /** AI proxy base URL for Anthropic API requests */
  aiProxyUrl: string;
  /** Proxy authentication headers (X-Proxy-Token) */
  proxyHeaders: Record<string, string>;
  /** Repository owner */
  repoOwner: string;
  /** Repository name */
  repoName: string;
  /** Event name (issue_comment, pull_request, etc.) */
  eventName: string;
  /** Bot user ID for the vibectl GitHub App */
  botUserId: string;
  /** Bot login name for the vibectl GitHub App */
  botLogin: string;
  /** CCA source path in container (default: /opt/cca) */
  ccaSourcePath?: string;
}

/**
 * Configure the container environment for CCA execution.
 *
 * Sets process.env variables that CCA's internal functions read.
 * This replaces CCA's OIDC-based token setup (token.ts) with
 * vibectl's direct credential injection.
 *
 * Returns the temp directory path used for GitHub Actions file-based outputs.
 */
export async function configureAuth(
  credentials: TaskCredentials,
): Promise<{ tempDir: string }> {
  // Create temp directory for @actions/core file-based outputs
  const tempDir = await mkdtemp(join(tmpdir(), "vibectl-"));

  // GitHub token — used by MCP servers and git operations
  process.env.GITHUB_TOKEN = credentials.githubToken;
  process.env.GH_TOKEN = credentials.githubToken;

  // AI proxy — transparent to Claude Code SDK
  // SDK sends to ANTHROPIC_BASE_URL, proxy injects real API key server-side
  process.env.ANTHROPIC_BASE_URL = credentials.aiProxyUrl;
  process.env.ANTHROPIC_API_KEY = "dummy-key-replaced-by-ai-proxy";

  // Proxy authentication headers
  const headerEntries = Object.entries(credentials.proxyHeaders);
  if (headerEntries.length > 0) {
    // Claude Code SDK reads ANTHROPIC_CUSTOM_HEADERS as JSON
    process.env.ANTHROPIC_CUSTOM_HEADERS = JSON.stringify(
      credentials.proxyHeaders,
    );
  }

  // Bot identity — read by constants.ts (Phase 2 patch)
  process.env.BOT_USER_ID = credentials.botUserId;
  process.env.BOT_LOGIN = credentials.botLogin;

  // CCA source path — used by install-mcp-server.ts for MCP server script paths
  process.env.GITHUB_ACTION_PATH = credentials.ccaSourcePath || "/opt/cca";

  // GitHub context env vars — read by various CCA components
  process.env.GITHUB_EVENT_NAME = credentials.eventName;
  process.env.GITHUB_SERVER_URL =
    process.env.GITHUB_SERVER_URL || "https://github.com";

  // Workflow token — used by CI MCP server for actions:read permission
  // In vibectl, the installation token serves both purposes
  process.env.DEFAULT_WORKFLOW_TOKEN = credentials.githubToken;

  // Runner temp directory — used by CCA for prompt files and execution output
  process.env.RUNNER_TEMP = tempDir;

  // @actions/core file-based output paths (defense-in-depth)
  // These files capture core.setOutput() and core.exportVariable() calls
  const outputFile = join(tempDir, "github-output");
  const envFile = join(tempDir, "github-env");
  await writeFile(outputFile, "");
  await writeFile(envFile, "");
  process.env.GITHUB_OUTPUT = outputFile;
  process.env.GITHUB_ENV = envFile;

  // Workspace directory — where the cloned repo lives in the container
  process.env.GITHUB_WORKSPACE = process.env.GITHUB_WORKSPACE || "/workspace";

  return { tempDir };
}
